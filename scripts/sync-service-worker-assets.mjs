import { createHash } from 'crypto';
import { readFileSync, writeFileSync } from 'fs';
import { join, posix } from 'path';

const ROOT_DIR = process.cwd();
const OUTPUT_FILE = join(ROOT_DIR, 'service-worker-assets.js');
const HTML_ENTRY_POINTS = ['index.html', 'time-sync-studio.html'];
const MANIFEST_FILE = 'manifest.json';

const read = (relativePath) => readFileSync(join(ROOT_DIR, relativePath), 'utf-8');

const toWebPath = (value, fromFile = '') => {
    if (!value || /^(https?:)?\/\//.test(value) || value.startsWith('data:') || value.startsWith('chrome-extension:')) {
        return null;
    }

    if (value.startsWith('/')) {
        return value;
    }

    const baseDir = fromFile ? posix.dirname(fromFile) : '.';
    return `/${posix.normalize(posix.join(baseDir, value))}`;
};

const fromWebPath = (webPath) => webPath.replace(/^\//, '');

const collectHtmlAssets = (htmlFile, assets, jsQueue) => {
    const html = read(htmlFile);
    const patterns = [
        { regex: /<link[^>]+href="([^"]+)"/g, kind: 'asset' },
        { regex: /<script[^>]+src="([^"]+)"/g, kind: 'script' },
    ];

    for (const { regex, kind } of patterns) {
        for (const match of html.matchAll(regex)) {
            const assetPath = toWebPath(match[1], htmlFile);
            if (!assetPath) {
                continue;
            }

            assets.add(assetPath);
            if (kind === 'script' && assetPath.endsWith('.js')) {
                jsQueue.add(assetPath);
            }
        }
    }
};

const IMPORT_REGEX = /import\s+(?:[^'"]+?\s+from\s+)?['"]([^'"]+)['"]/g;

const collectJsDependencies = (entryWebPath, assets, visited) => {
    if (visited.has(entryWebPath)) {
        return;
    }
    visited.add(entryWebPath);

    const relativePath = fromWebPath(entryWebPath);
    const source = read(relativePath);

    for (const match of source.matchAll(IMPORT_REGEX)) {
        const importedPath = toWebPath(match[1], relativePath);
        if (!importedPath || !importedPath.endsWith('.js')) {
            continue;
        }

        assets.add(importedPath);
        collectJsDependencies(importedPath, assets, visited);
    }
};

const collectManifestAssets = (manifestFile, assets) => {
    const manifestWebPath = toWebPath(manifestFile);
    if (manifestWebPath) {
        assets.add(manifestWebPath);
    }

    const manifest = JSON.parse(read(manifestFile));
    for (const icon of manifest.icons || []) {
        const assetPath = toWebPath(icon.src, manifestFile);
        if (assetPath) {
            assets.add(assetPath);
        }
    }
};

const assets = new Set(['/', '/index.html', '/time-sync-studio.html']);
const jsQueue = new Set();

for (const htmlFile of HTML_ENTRY_POINTS) {
    collectHtmlAssets(htmlFile, assets, jsQueue);
}

for (const jsEntry of jsQueue) {
    collectJsDependencies(jsEntry, assets, new Set());
}

collectManifestAssets(MANIFEST_FILE, assets);

const sortedAssets = [...assets].sort();
const version = createHash('sha256')
    .update(JSON.stringify(sortedAssets))
    .digest('hex')
    .slice(0, 10);

const output = `/* Auto-generated by scripts/sync-service-worker-assets.mjs. Do not edit by hand. */
self.__STATIC_ASSET_VERSION = '${version}';
self.__STATIC_ASSETS = ${JSON.stringify(sortedAssets, null, 4)};
`;

writeFileSync(OUTPUT_FILE, output);
console.log(`[service-worker] synced ${sortedAssets.length} assets -> ${version}`);
